local function normalizeKey(key)
	if type(key) ~= "string" then
		return nil
	end
	return string.upper((key:gsub("[^%w]+", "_"):gsub("^_+", ""):gsub("_+$", "")))
end

function UIIconAssets.getAssetId(key)
	local normalized = normalizeKey(key)
	if not normalized then
		return nil
	end
	return UIIconAssets.Raw[normalized]
end

function UIIconAssets.getImage(key)
	local assetId = UIIconAssets.getAssetId(key)
	if not assetId then
		return nil
	end
	return "rbxassetid://" .. assetId
end

function UIIconAssets.getThumb(key, size)
	local assetId = UIIconAssets.getAssetId(key)
	if not assetId then
		return nil
	end
	size = tonumber(size) or 420
	return string.format("rbxthumb://type=Asset&id=%s&w=%d&h=%d", assetId, size, size)
end

return UIIconAssets

